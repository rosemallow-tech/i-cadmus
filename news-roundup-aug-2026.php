          <div class="callout-title">I-CADMUS Connection</div>
          <p>Food deception extends beyond substituting one ingredient or species for another. It can involve Addition, Dilution, Misrepresentation and Undisclosed information, supported by weaknesses in labelling rules, surveillance and enforcement. The central lesson is simple: a label may be technically compliant yet still fail to give consumers a truthful and understandable picture of the food they are buying.</p>
        </div>

        <h2>What Consumers Can Do: Becoming an Informed Advocate</h2>

        <p>To protect yourself and drive supply chain integrity, consumers should adopt a more active role at the point of purchase:</p>

        <ul>
          <li><strong>Ask Direct Questions:</strong> Don't hesitate to ask your fishmonger or server specific details about the fish: Where was it caught? What is the exact common species name? Was it wild or farmed? Legitimate, transparent sellers will know or be eager to find out.</li>
          <li><strong>Buy Whole or Less Processed:</strong> Purchasing whole fish (or fish with the skin on) makes species substitution drastically harder for fraudsters to pull off.</li>
          <li><strong>Beware of "Too Good to Be True" Deals:</strong> Premium wild-caught species command high market prices due to harvest and management costs. If a menu or display offers wild red snapper or cod at bargain-basement prices, exercise caution.</li>
          <li><strong>Demand Chain-of-Custody Integrity:</strong> Support retailers, restaurants, and national frameworks that enforce strict, verifiable, end-to-end traceability from harvest to plate.</li>
        </ul>

