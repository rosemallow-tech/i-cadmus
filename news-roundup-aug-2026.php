        <h2>Illegal Lobster Fishing in Canada: A Growing Crisis</h2>

        <p>The illegal lobster fishing in Canada is a significant issue that affects the marine environment and the economy. The federal Department of Fisheries and Oceans (DFO) suspects that hundreds of millions of dollars' worth of lobster is caught in Atlantic Canadian waters each year but never reported to authorities. This unreported catch raises both income tax and conservation implications for the country's largest fishery. The DFO has been examining unreported catches in the lobster sector, estimating that between 10 and 30 percent of lobster landings in the region are unreported. The department is working to map out criminal networks and money laundering in the sector.</p>

        <p>The fight against illegal lobster fishing is not only a matter of compliance with regulations but also a fight for the sustainability of the lobster population. The industry has faced challenges due to unreported catches, which have caused significant economic losses and disrupted supply chains. The DFO's crackdown on illegal fishing practices has included trap seizures, vessel confiscations, and arrests, aiming to level the playing field for legal harvesters.</p>

        <p>The issue of illegal lobster fishing has also led to divisions within coastal communities and between commercial fishers and Indigenous treaty fishing communities. The Mi'kmaw fishers, for instance, face allegations from some in the commercial industry that they're fuelling crime and threatening lobster stocks. However, the industry has brought in a record-setting amount of lobster in subsequent years, and the health of the lobster population is currently ranked in "the healthy zone."</p>

        <p>The Royal Canadian Mounted Police (RCMP), Department of Fisheries and Oceans (DFO), and Nova Scotia Department of Natural Resources officers have arrested multiple individuals in simultaneous raids in Clare, Nova Scotia, who are linked to a crime ring allegedly connected to illegal lobster fishing and drug smuggling.</p>

        <h2>Poaching for Prizes: Illegal Fishing on the Great Barrier Reef</h2>

        <p>Four alleged fish poachers have been caught fishing illegally in a no-take zone in the southern Capricorn Bunker Group during a local fishing competition &mdash; and now face about $14,500 in fines.</p>

        <p>Reef Authority compliance officers nabbed the group during targeted night patrols off Bundaberg on the weekend of a fishing competition in July after detecting a recreational vessel fishing inside a Marine National Park (Green) zone. Source: <a href="https://www.linkedin.com/pulse/reef-brief-august-2026-great-barrier-reef-marine-park-aut-i7vnc/" target="_blank" rel="noopener">Reef Brief — August 2026</a>.</p>

        <blockquote>
          <p>"This wasn't just illegal fishing &mdash; it was a blatant attempt to cheat fellow competitors out of prizes." &mdash; Owen Witt, Reef Authority Compliance Officer.</p>
        </blockquote>

        <p>In a separate incident on 24 July 2026, another four alleged fish poachers were caught red-handed illegally fishing in a no-take zone off Yeppoon. Reef Authority compliance officers intercepted the vessel during a targeted night patrol in the Capricorn Bunker Group, allegedly finding fishing lines in the water and an esky containing freshly caught reef fish.</p>

        <blockquote>
          <p>"What illegal fishers need to understand is that just because you can't see us, doesn't mean we can't see you. Compliance doesn't stop when the sun goes down." &mdash; Chris Cochrane, Reef Authority Compliance Director.</p>
        </blockquote>

        <p>Research shows these Green Zones act as fish nurseries, with up to 60 per cent of juvenile coral trout in some fished areas coming from nearby Green Zones. Illegal fishing threatens those benefits and undermines the overwhelming majority of fishers who understand the rules and do the right thing. Source: <a href="https://www2.gbrmpa.gov.au/news/illegal-fishers-busted-red-handed" target="_blank" rel="noopener">Great Barrier Reef Marine Park Authority</a>.</p>

        <h2>IUU Fishing in Africa: A $9 Billion Crisis</h2>

        <p>Up to 40% of fish caught in African waters may be illegal, costing the continent over $9 billion every year. Illegal, Unreported, and Unregulated (IUU) fishing is on the rise, directly impacting the health of our oceans and threatening the economic stability of coastal communities that depend on the sea.</p>

        <ul>
          <li>Illegal fishing involves operations conducted without permission and often in violation of established laws.</li>
          <li>Unreported fishing occurs when catches are hidden or misreported, undermining vital monitoring systems.</li>
          <li>Unregulated fishing describes fishing in areas lacking proper conservation and management oversight, leading to zero accountability.</li>
        </ul>

        <p>Fish remains a critical source of affordable protein for millions of people across Africa. Source: <a href="https://www.linkedin.com/company/wild-africa-org/posts/?feedView=all" target="_blank" rel="noopener">Wild Africa</a>.</p>

