        <p>Illegal, unreported and unregulated fishing is often imagined as a mysterious vessel operating far offshore.</p>

        <p>That is only the beginning of the story.</p>

        <p>For illegal fishing to remain profitable, its catch eventually has to move. It may be landed, transhipped, transported, processed, documented, mixed with legitimate product, imported, wholesaled, retailed or served.</p>

        <p>Somewhere along that journey, illegal catch can acquire the appearance of legitimate seafood.</p>

        <p>That is where illegal fishing meets seafood fraud &mdash; and why I-CADMUS follows the fish all the way from ocean to plate.</p>


        <h2>The numbers should make us pay attention</h2>

        <p>One of the most important developments of the month was new research examining the workings of illegal fishing markets.</p>

        <p>Researchers Philippe Le Billon, Zelda Ladefoged and U. Rashid Sumaila estimate annual illicit marine wild-capture seafood trade at approximately 8.4&ndash;15.4 million tonnes, worth US$6.2&ndash;12.2 billion.</p>

        <p>Industrial-scale fleets were estimated to account for 82&ndash;93% of illicit volume, while roughly two-thirds of illicit seafood trade by value originated from fishing grounds in West Africa, East Asia and Southeast Asia.</p>

        <p>The research describes ways in which illicit seafood can move towards legitimate markets: transshipment, weakly controlled ports, opaque ownership structures, documentation fraud and the mixing of legal and illegal product.</p>

        <p>Technology is certainly improving our ability to detect suspicious activity. Satellites, electronic vessel identification, cameras, sensors, drones and artificial intelligence are progressively illuminating activity that once disappeared over the horizon.</p>

        <p>But technology alone cannot solve the problem.</p>

        <p>Someone still has to inspect the vessel.<br>
        Someone has to verify the paperwork.<br>
        Someone has to inspect the processor, truck, importer or market.<br>
        Someone has to investigate suspicious transactions.<br>
        And, ultimately, someone has to decide that buying cheap seafood of doubtful origin is unacceptable.</p>

        <p>The illegal act may occur at sea. The economic reward occurs when somebody successfully sells the seafood.</p>


        <h2>Australia: two different illegal seafood problems</h2>

        <p>September provided Australia with examples of both sides of the equation.</p>

        <p>Six Indonesian nationals pleaded guilty in Darwin Local Court on 1 September to fishing illegally in Australian waters following the apprehension of a vessel near Little Adolphus Island in the Torres Strait. Authorities reported finding fishing equipment and approximately 700 kg of salt, commonly used to preserve sea cucumber.</p>

        <p>On 9 September, Operation LUNAR intercepted another foreign vessel near Australia&rsquo;s Exclusive Economic Zone boundary north of the Wessel Islands. Authorities reported evidence of suspected fisheries offences and seized approximately 100 kg of fresh and dried reef fish and fish roe.</p>

        <p>Then on 14 September, Operation BROADSTAFF detected another Indonesian fishing vessel northwest of Badu Island in the Torres Strait. Authorities reported seizing 108 reef fish, 29 sharks and fishing equipment.</p>

        <p>Those operations matter.</p>

        <p>But Australians should not conclude that illegal seafood is exclusively something brought into our waters by foreign vessels.</p>

        <p>An ABC 7.30 investigation in September turned attention towards the domestic illicit seafood trade &mdash; recreational and commercial catch allegedly being poached or diverted for black-market sale.</p>

        <p>NSW Fisheries allowed 7.30 to accompany officers during inspections in Sydney. At one premises officers encountered incorrectly labelled packages of abalone, although receipts were produced showing the product had been legally purchased and investigations continued.</p>

        <p>Victorian seafood wholesaler Peter Jenkins told the program he had repeatedly been offered illegal seafood. Victorian Fisheries Authority CEO Travis Dowling described cases involving illegally taken abalone being offered for sale from plastic shopping bags on extremely hot days.</p>

        <p>That exposes an important consumer issue.</p>

        <p><strong>Illegal seafood can also become unsafe seafood.</strong></p>

        <p>Licensing, cold-chain requirements, harvest controls, closed areas, traceability and documentation are not bureaucratic decorations. They form part of the system intended to protect resources, legitimate businesses and consumers.</p>


        <h2>Canada: follow the lobster</h2>

        <p>Canada supplied an excellent example of authorities following seafood beyond the point of harvest.</p>

        <p>Fishery officers conducted operations against lobster-processing facilities in the Maritimes, focusing on processors suspected of handling lobster harvested outside regulated seasons, without proper documentation, or from unlicensed sources.</p>

        <p>Using an approach that combined physical inspections with analysis of purchasing records, catch logs and licence data, officers were able to identify discrepancies between documented inputs and processing outputs.</p>

        <p>Separately, in British Columbia the Canadian Food Inspection Agency (CFIA) warned consumers about Pacific oysters, mussels and clams harvested from an area closed under the Canadian Shellfish Sanitation Program.</p>

        <p>Officers seized 136 Pacific oysters, eight mussels and two Manila clams.</p>

        <p>The Canadian authorities&rsquo; warning deserves attention: harvesting from closed areas can be both illegal and unsafe.</p>

        <p>Again, resource management, seafood integrity and consumer protection intersect.</p>


        <h2>Sri Lanka: from blast fishing to 9,000 sea cucumbers</h2>

        <p>Sri Lanka produced some of September&rsquo;s most confronting enforcement examples.</p>

        <p>The Sri Lanka Navy reported numerous operations involving banned fishing methods and gear. Between 1 and 11 September alone, 65 people were apprehended, with 26 dinghies and other vehicles also seized.</p>

        <p>In another operation, more than 1,900 kg of illegally caught fish was seized off Chundikulam and Kaddaikadu.</p>

        <p>On 15 September, authorities intercepted a vehicle carrying more than 370 kg of fish suspected of having been caught using explosives.</p>

        <p>The same day, another operation recovered an extraordinary 9,000 illegally harvested sea cucumbers from two dinghies in Jaffna Lagoon.</p>

        <p>Later in the month, authorities seized another approximately 300 kg of fish suspected to have been caught using explosives in Mannar.</p>

        <p>Destructive fishing demonstrates why the word <em>illegal</em> should never be dismissed as merely an administrative classification.</p>

        <p>The consequences can extend through ecosystems, future fish populations, legitimate fishers, coastal communities and ultimately seafood supply.</p>


        <h2>Indonesia: when the document itself becomes part of the problem</h2>

        <p>A particularly interesting September case takes I-CADMUS beyond illegal harvesting.</p>

        <p>Indonesia&rsquo;s Ministry of Marine Affairs and Fisheries reported uncovering suspected falsification of a fishing-vessel operational document &mdash; a <em>Standar Laik Operasi</em> or SLO &mdash; in Kendari, Southeast Sulawesi.</p>

        <p>According to the Ministry, examination of the electronic issuing system found that the purported document was not recorded there, and a suspect was identified.</p>

        <p>The significance for seafood integrity is greater than one allegedly falsified document.</p>

        <p>Traceability systems depend upon documents being trustworthy.</p>

        <p>If vessel authorisations, catch records, certificates, invoices, origin declarations or other documents can be falsified, a seafood supply chain can look compliant on paper while concealing something very different underneath.</p>

        <p>That is why this case potentially crosses several I-CADMUS categories:</p>

        <div class="case-card">
          <div class="case-card-label">I-CADMUS Categories Engaged</div>
          <p><strong>I &mdash; Illegal:</strong> The alleged falsification of an official vessel document is itself a legal offence.</p>
          <p><strong>C &mdash; Counterfeit:</strong> A fabricated or falsified official document is, by definition, counterfeit.</p>
          <p><strong>U &mdash; Unreported / Unregulated / Undisclosed:</strong> A vessel operating under a falsified authorisation operates outside the regulated system.</p>
        </div>

        <p>It demonstrates something fundamental:</p>

        <blockquote>
          <p>Traceability is only as trustworthy as the information entering the system.</p>
        </blockquote>


        <h2>Philippines: enforcement increasingly requires partnerships</h2>

        <p>In Albay in the Philippines, authorities reported the arrest of 20 people and seizure of boats and fishing equipment valued at approximately PHP4 million during anti-illegal-fishing operations.</p>

        <p>Significantly, the operation involved fisheries enforcement personnel working with police, the Philippine Army and Coast Guard.</p>

        <p>That multi-agency approach is increasingly important.</p>

        <p>Illegal seafood can cross the responsibilities of fisheries authorities, customs, border agencies, police, food regulators, taxation authorities, transport regulators and consumer-protection bodies.</p>

        <p>No single agency necessarily sees the entire journey.</p>


        <h2>Europe: keeping known IUU operators out of legitimate markets</h2>

        <p>Europe also moved at the regulatory level.</p>

        <p>On 14 September the European Commission adopted an implementing regulation updating the EU list of vessels engaged in illegal, unreported and unregulated fishing.</p>

        <p>This illustrates another critical principle.</p>

        <p>Successful IUU policy cannot depend solely upon catching a vessel while it is fishing illegally.</p>

        <blockquote>
          <p>Market access matters. Ports matter. Documentation matters. Import controls matter. Beneficial ownership matters. And preventing known illegal operators from simply moving catch into another market matters.</p>
        </blockquote>


        <h2>Ten years of closing ports to illegal catch</h2>

        <p>September also marked an important international anniversary.</p>

        <p>FAO commemorated ten years since the entry into force of the Agreement on Port State Measures &mdash; PSMA, the world&rsquo;s first binding international agreement specifically targeting IUU fishing.</p>

        <p>The concept is powerful: rather than attempting to police every square kilometre of ocean, deny vessels engaged in IUU fishing access to the ports through which they need to land their catch.</p>

        <p>The Agreement now has 86 Parties representing 110 FAO Members.</p>

        <p>And the system is becoming more sophisticated.</p>

        <p>During September, FAO expanded analytics within its PSMA Global Information Exchange System to provide information on inspection levels, apparent infringements and other indicators.</p>

        <p>In Ghana, FAO-supported training for fisheries officers covered risk assessment, fisheries monitoring centres and &mdash; importantly &mdash; sea, port, transport and market inspections, together with enforcement.</p>

        <p>Read that sequence again: <strong>Sea &rarr; Port &rarr; Transport &rarr; Market.</strong></p>

        <p>That is a seafood supply chain.</p>

        <p>And that is precisely why I-CADMUS argues that illegal seafood must be treated as a supply-chain integrity problem, not only a fisheries-management problem.</p>


        <h2>The I-CADMUS connection</h2>

        <p>September&rsquo;s cases show why the seven I-CADMUS categories cannot always be placed into separate boxes.</p>

        <ul class="icadmus-category-list">
          <li><strong>I &mdash; Illegal:</strong> Illegal harvesting, poaching, prohibited methods and incursions into another country&rsquo;s waters.</li>
          <li><strong>C &mdash; Counterfeit:</strong> False or falsified documents and credentials can help disguise the true status of seafood or vessels.</li>
          <li><strong>A &mdash; Addition/Adulteration:</strong> Integrity controls must identify interventions capable of altering seafood or concealing quality and condition.</li>
          <li><strong>D &mdash; Dilution:</strong> Economic deception can continue further along the chain through water addition, glazing or weight manipulation.</li>
          <li><strong>M &mdash; Misrepresentation/Mislabelling:</strong> Once origin, species, production method or legality becomes obscured, seafood can be presented to buyers as something it is not.</li>
          <li><strong>U &mdash; Unreported/Unregulated/Undisclosed:</strong> Unreported catches, hidden ownership, undocumented transfers and traceability gaps create the darkness in which illicit trade flourishes.</li>
          <li><strong>S &mdash; Substitution:</strong> Once identity is lost, lower-value or different species can potentially replace what the consumer believes they are purchasing.</li>
        </ul>

        <p>Not every case involves all seven.</p>

        <p>But September demonstrates how one form of seafood integrity failure can create the conditions for another.</p>


        <h2>The consumer is part of the IUU equation</h2>

        <p>Consumers rarely meet the person who caught their fish.</p>

        <p>We encounter seafood after harvesting, landing, transshipment, transport, processing, importing, wholesaling, retailing or cooking.</p>

        <p>By then an illegally caught fish may look exactly like a legally caught one.</p>

        <p>That means traceability ultimately has to answer more than: <em>What species is this?</em></p>

        <p>We increasingly need to be able to ask:<br>
        Where was it caught? Who caught it? Was the vessel authorised? Was the catch reported? Was the fishing method legal? Was it landed through an authorised port? Can its documents be independently verified? Has its identity survived every transaction? And can the final consumer trust the description attached to it?</p>


        <h2>September&rsquo;s I-CADMUS lesson: follow the fish &mdash; and follow the money</h2>

        <p>Patrol boats matter. Satellite surveillance matters. DNA testing matters. Digital catch documentation matters. Port inspections matter.</p>

        <p>But none of them alone will eliminate illegal seafood.</p>

        <p>An effective integrity system requires connected defences:</p>

        <blockquote>
          <p>Detection &rarr; Interdiction &rarr; Verification &rarr; Enforcement &rarr; Traceability &rarr; Market Exclusion &rarr; Consumer Transparency</p>
        </blockquote>

        <p>Break enough of those links and illicit product can find a route to market.</p>

        <p>Connect them and the economics of illegal fishing begin to change.</p>

        <p>That may ultimately be September&rsquo;s most important lesson.</p>

        <p><strong>Illegal fishing survives because there is money to be made from it.</strong></p>

        <p>The ocean may be where illegal seafood begins. The market is where illegal fishing gets paid. And transparency, traceability, professional responsibility and informed consumers are among the ways we can stop rewarding it.</p>

        <div class="callout">
          <div class="callout-title">The I-CADMUS Position</div>
          <p>Illegal seafood is a supply-chain integrity problem. Following the fish from ocean to plate &mdash; and following the money from market back to vessel &mdash; is the only way to break the economics that sustain it.</p>
          <p><em>A Special Initiative of the Seafood Consumers Association Limited</em></p>
        </div>

