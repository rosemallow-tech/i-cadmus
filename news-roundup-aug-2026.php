        <h2>Canada: Illegal Fishing Enforcement in New Brunswick</h2>

        <p>On July 8, 2026, fishery officers in Southwest New Brunswick arrested one individual and ticketed them for being above the daily bag limit for trout on 5 Mile Brook, a tributary of the Southwest Miramichi River. The individual received a fine of $2,600 and their gear and catch were seized.</p>

        <p>A conservation officer from New Brunswick assisted fishery officers with the inspection that led to the arrest.</p>

        <p>Daily limits for angling are enforced to ensure the conservation of species. Catching above the daily limit can jeopardize species conservation and the future viability of both commercial and recreational fisheries. To report suspected unauthorized fishing activity, please contact your <a href="https://ow.ly/Cc7v50Zwkv1" target="_blank" rel="noopener">local Conservation and Protection detachment</a>.</p>

        <h2>Recreational Harvester Fined $5,500 for Multiple Fisheries Act Violations in British Columbia</h2>

        <p>On March 31, 2026, in British Columbia Provincial Court, Braden Lee Herback pled guilty to multiple offences under the Fisheries Act, was fined $5,500 and received a one-year fishing prohibition for failing to record catch information; retaining an undersized Chinook salmon; possessing 15 spot prawns carrying eggs contrary to licence conditions; and retaining four Dungeness crabs in a condition that prevented fishery officers from determining their size and sex.</p>

        <p>Source: Fisheries and Oceans Canada, July 29, 2026.</p>

        <p>DFO reminds recreational harvesters that fishing licence conditions, catch recording requirements, size limits and species-specific retention rules are essential to protecting fish populations and supporting sustainable fisheries. Harvesting undersized fish, retaining egg-bearing prawns, or altering fish and shellfish to prevent compliance verification are serious offences that can harm fish stocks and reduce benefits for Indigenous communities, coastal economies and future generations. Anyone with information about suspected fisheries violations in B.C. or Yukon can call DFO Pacific Region's toll-free violation reporting line at 1-800-465-4336, or email <a href="mailto:DFO.ORR-ONS.MPO@dfo-mpo.gc.ca">DFO.ORR-ONS.MPO@dfo-mpo.gc.ca</a>.</p>

        <h2>Food Recalls in Australia on the 'Up'</h2>

        <p>It is late July 2026 and already Australia has had 41 food recalls: 41% were for undeclared allergens and the other 60% covers microbiological, chemical, foreign objects and secondary fermentation hazards. They cut across every industry sector. Quote from <a href="https://www.linkedin.com/in/integrity-compliance/" target="_blank" rel="noopener">Clare Winkel</a> — Are standards slipping?</p>

        <h2>Criminal Catches: When Seafood Import Controls Fail</h2>

        <p>A report from the Coalition for Fisheries Transparency warns that the United Kingdom remains vulnerable to seafood associated with illegal, unreported and unregulated fishing, despite having a formal catch-certification and import-control system.</p>

        <p><em>Criminal Catches: How to Stop the Supply of Illegal Seafood to the UK</em> examines whether the UK is adequately checking the legality of seafood entering its market. Its conclusion is sobering &mdash; regulations and catch certificates provide an important foundation, but they offer limited protection when verification rates are low, enforcement information is fragmented and authorities rarely refuse suspicious consignments.</p>

        <p>In 2024, the UK imported approximately 656,000 tonnes of seafood from 110 countries. Forty-eight of those countries were considered high risk for IUU fishing, while 23 had previously received warnings or sanctions under the European Union's IUU "carding" system. More than one-quarter of UK seafood imports reportedly came from countries that had been yellow-carded or ranked among those at greatest global risk of IUU fishing.</p>

        <p>The report uses case studies involving supermarket tuna, Russian whitefish, squid and Ghanaian fisheries to demonstrate how seafood can pass through complex international supply chains before reaching consumers. Processing or trans-shipment through intermediary countries may obscure the original fishing vessel, fishing grounds, ownership and labour conditions.</p>

        <p>This is not only an environmental or fisheries-management concern. IUU fishing is frequently connected with forced labour, debt bondage, unsafe working conditions and other serious human-rights abuses. Consumers may therefore unknowingly purchase seafood caught illegally or produced through exploitation.</p>

        <p>The Coalition recommends substantially increasing the verification of catch certificates, digitising the import-control system, collecting more detailed vessel and supply-chain information, applying risk-based physical inspections and publishing annual enforcement results. It also calls for labour-related information to be incorporated into import controls.</p>

        <p>One of its most significant proposals is a UK "carding" system. Countries failing to combat IUU fishing would first receive a warning &mdash; or yellow card &mdash; and could ultimately lose access to the UK seafood market through a red card. This would turn market access into a practical incentive for better fisheries governance.</p>

        <blockquote>
          <p>For I-CADMUS, the report reinforces an essential principle: documentation is not proof unless it is verified. Effective seafood integrity requires information to be collected, connected, tested and acted upon.</p>
        </blockquote>

        <p>Consumers should not have to choose between seafood and certainty. Governments, importers and retailers must be able to demonstrate not only what a seafood product is and where it came from, but also whether it was caught legally and without human exploitation.</p>

        <h2>Duped: Food Exposed &mdash; How Labels and Marketing Can Mislead Consumers</h2>

        <p>In late July and early August 2026, ABC TV's Four Corners broadcast a two-part investigation, <em>Duped: Food Exposed</em>, examining food fraud, product authenticity, misleading labels and the marketing techniques used to influence Australian consumers.</p>

        <p>The first episode investigated whether food products were what their labels claimed. Independent testing and confidential government records raised concerns involving product origin, ingredient authenticity, possible meat substitution and breaches of Australian food laws. The investigation included questions about the origins of tomato products and warnings that Australians may previously have consumed undeclared horse meat. These examples demonstrate the essential role of scientific testing, traceability, regulatory intelligence and transparent enforcement in protecting consumers.</p>

        <p>The second episode examined a more subtle form of potential deception: ultra-processed foods made to appear healthier or more natural than their composition might suggest. Industry insiders described how products can be engineered around combinations of sugar, salt, fat, flavour and texture, while packaging emphasises fruit imagery, protein, "natural" ingredients or health-star ratings. The ABC identified children's products promoted through fruit and yoghurt claims that nevertheless contained very high proportions of sugar. It also highlighted that terms such as "natural" have no clear legal definition in Australian food law.</p>

        <p>The investigation identified a broader regulatory failure. Fifteen years after the 2011 Labelling Logic review recommended substantial reform, analysis cited by the ABC found that only three of its 40 public-health recommendations had been fully implemented &mdash; and all three related to alcohol. Proposed improvements, including clearer disclosure of added sugars, were reportedly delayed or abandoned while regulatory cost and industry burden were given significant weight.</p>

        <p>Not every questionable marketing claim necessarily constitutes criminal food fraud. However, the Four Corners investigation demonstrates the grey area in which selective information, ambiguous terminology, technically compliant labels and carefully constructed imagery can create an overall impression that consumers may reasonably misunderstand.</p>

        <p><a href="https://www.abc.net.au/news/2026-07-29/processed-food-marketing-fooling-shoppers-over-health-claims/106961954" target="_blank" rel="noopener">Read the ABC investigation</a> and view the <a href="https://www.abc.net.au/news/programs/4corners" target="_blank" rel="noopener">Four Corners</a> series, <em>Duped: Food Exposed</em>.</p>

